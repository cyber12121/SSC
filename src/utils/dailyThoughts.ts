/**
 * Generates a deterministic integer hash for a date string 'YYYY-MM-DD'.
 * Ensures that all sessions on the same calendar day see the same quote,
 * but it changes automatically to a new random quote every day.
 */
function hashDate(dateStr: string): number {
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    const char = dateStr.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0; // Convert to 32bit integer
  }
  return Math.abs(hash);
}

/**
 * Returns a randomized thought that changes automatically every day.
 * If salt is provided, returns a different thought (for manual refresh).
 */
export function getDailyThought(salt = 0): DailyThought {
  const today = new Date();
  const dateKey = `${today.getFullYear()}-${today.getMonth() + 1}-${today.getDate()}`;
  const baseHash = hashDate(dateKey);
  const index = (baseHash + salt) % DAILY_THOUGHTS.length;
  return DAILY_THOUGHTS[index];
}
